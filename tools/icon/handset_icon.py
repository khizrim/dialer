"""Ozero Phone launcher icon: writes ic_launcher_foreground.xml and ic_launcher_monochrome.xml.
Needs: pip install cairosvg shapely svgpathtools. Run from this folder: python3 handset_icon.py [--solve]
paste.py drops a candidate onto a real home-screen screenshot for checking."""
import json, geo
from geo import parts, THEMES
# Chosen variant (2026-11-07): ink mass ~ Ozero Mail ring (app#242), stroke 7.4dp
# (1.4x the old 5.2dp), outline inflated 1.2 units so the counter survives,
# water line at 44% of the mark, optical centre at (54, 55.2) like Mail.
if __name__=='__main__' and '--solve' in __import__('sys').argv:
    p,_=geo.build(1.72,7.4/1.72,1.2,wlf=.44); print(p)
else:
    p=dict(K=1.72,w=7.4/1.72,d=1.2,blue=1.1,cx=50.1853,cy=55.1521,wl=51.4702,shift=5.16)
top,bot=parts(p)
top=top.simplify(.015); bot=bot.simplify(.015)
def pd(g): return geo.topath(g)
wl=p['wl']; ty0=top.bounds[1]; by1=bot.bounds[3]
L=THEMES['light']
H='''<?xml version="1.0" encoding="utf-8"?>
<!-- %s -->
<!-- Generated by tools/icon/handset_icon.py; edit the generator, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
'''
def grad(y0,y1,c0,c1):
    return f'''        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="0" android:startY="{y0:.2f}" android:endX="0" android:endY="{y1:.2f}"
                android:startColor="#FF{c0[1:].upper()}" android:endColor="#FF{c1[1:].upper()}" />
        </aapt:attr>
'''
fg=H%'The refracted handset: the ink warms toward the water line, the water is brightest just under it, as in Ozero Mail.'
fg+=f'    <path android:fillType="evenOdd" android:pathData="{pd(top)}">\n'+grad(ty0,wl,*L['top'])+'    </path>\n'
fg+=f'    <path android:fillType="evenOdd" android:pathData="{pd(bot)}">\n'+grad(wl,by1,*L['bot'])+'    </path>\n</vector>\n'
mono=(H%'The same mark in one colour for themed icons.').replace('    xmlns:aapt="http://schemas.android.com/aapt"\n','')
mono+=f'    <path android:fillType="evenOdd" android:fillColor="#FF000000" android:pathData="{pd(top)}" />\n'
mono+=f'    <path android:fillType="evenOdd" android:fillColor="#FF000000" android:pathData="{pd(bot)}" />\n</vector>\n'
import os; R=os.path.join(os.path.dirname(__file__),"../../app/src/main/res/drawable/")
open(R+'ic_launcher_foreground.xml','w').write(fg); open(R+'ic_launcher_monochrome.xml','w').write(mono)
print(len(fg),len(mono), sum(len(r.coords) for g in [top,bot] for pg in getattr(g,'geoms',[g]) for r in [pg.exterior,*pg.interiors]))
