"""Ozero Phone launcher icon: writes ic_launcher_foreground.xml and ic_launcher_monochrome.xml.
Khizri, 2026-11-08: the classic handset from their reference (handset_outline.json, traced),
in Ozero Mail's language (ozeromail/app#242): chopped flat terminals like the ring's cuts,
halves meeting at the water line with no gap, the lower half shifted right by Mail's 21%,
Mail's water-line gradients, the same ink mass as the ring. Centred on its bounding box.
Needs: pip install shapely numpy. Run: python3 handset_icon.py"""
import json, os
import numpy as np
from shapely.geometry import Polygon, box
from shapely import affinity
HERE = os.path.dirname(os.path.abspath(__file__))
H, WLF, SHIFT = 42.0, .53, .21        # mark height (dp of 108), water line (share), shift (share of width)
CHOP = [(-95, 18), (15, 22)]           # flatten the earpiece and mouthpiece tips: (direction°, depth in outline px)
G = Polygon(json.load(open(os.path.join(HERE, 'handset_outline.json'))))
for ang, dep in CHOP:
    n = np.array([np.cos(np.radians(ang)), np.sin(np.radians(ang))]); t = np.array([-n[1], n[0]])
    c = n * ((np.array(G.exterior.coords) @ n).max() - dep); L = 900
    G = G.difference(Polygon([c + t * L, c - t * L, c - t * L + n * L, c + t * L + n * L]))
b = G.bounds; k = H / (b[3] - b[1]); G = affinity.scale(G, k, k, origin=(0, 0)); b = G.bounds
sh = SHIFT * (b[2] - b[0])
G = affinity.translate(G, 54 - (b[0] + b[2] + sh) / 2, 54 - (b[1] + b[3]) / 2); b = G.bounds
wl = b[1] + WLF * (b[3] - b[1])
top = G.intersection(box(-9, -9, 117, wl)).simplify(.01)
bot = affinity.translate(G.buffer(H * .006), sh, 0).intersection(box(-9, wl, 117, 117)).simplify(.01)  # water part 10% heavier
def path(g):
    s = ''
    for pg in getattr(g, 'geoms', [g]):
        if pg.geom_type != 'Polygon' or pg.area < .5: continue
        c = list(pg.exterior.coords)[:-1]; s += 'M' + ' '.join(f'{x:.2f},{y:.2f}' for x, y in c) + 'Z'
    return s
def grad(y0, y1, c0, c1):
    return (f'        <aapt:attr name="android:fillColor">\n            <gradient android:type="linear" android:startX="0" android:startY="{y0:.2f}" android:endX="0" android:endY="{y1:.2f}"\n'
            f'                android:startColor="#FF{c0}" android:endColor="#FF{c1}" />\n        </aapt:attr>\n')
HEAD = '''<?xml version="1.0" encoding="utf-8"?>
<!-- %s -->
<!-- Generated by tools/icon/handset_icon.py; edit the generator, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"%s
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
'''
fg = HEAD % ('The handset in Ozero Mail\'s language: ink warming toward the water line, water brightest just under it, lower half shifted.', '\n    xmlns:aapt="http://schemas.android.com/aapt"')
fg += f'    <path android:pathData="{path(top)}">\n' + grad(top.bounds[1], wl, '101A2E', '2C4A80') + '    </path>\n'
fg += f'    <path android:pathData="{path(bot)}">\n' + grad(wl, bot.bounds[3], '50A0FF', '1A6FE0') + '    </path>\n</vector>\n'
mono = HEAD % ('The same mark in one colour for themed icons.', '') + f'    <path android:fillColor="#FF000000" android:pathData="{path(top)}" />\n    <path android:fillColor="#FF000000" android:pathData="{path(bot)}" />\n</vector>\n'
R = os.path.join(HERE, '../../app/src/main/res/drawable/')
open(R + 'ic_launcher_foreground.xml', 'w').write(fg); open(R + 'ic_launcher_monochrome.xml', 'w').write(mono)
