"""Ozero Phone launcher icon: writes ic_launcher_foreground.xml and ic_launcher_monochrome.xml.
Direction chosen by Khizri on 2026-11-08 (their reference image): a solid classic handset,
flat navy above the water line, flat blue below, a thin paper gap at the line, no shift.
The outline (handset_outline.json) is traced from that reference. Centred on its bounding box.
Needs: pip install shapely. Run: python3 handset_icon.py"""
import json, os
from shapely.geometry import Polygon, box
from shapely import affinity
HERE = os.path.dirname(os.path.abspath(__file__))
NAVY, BLUE = 'FF072353', 'FF0080FE'
H, WLF, GAP = 42.0, .53, 1.3          # mark height (dp of 108), water line (share of height), gap (dp)
G = Polygon(json.load(open(os.path.join(HERE, 'handset_outline.json'))))
b = G.bounds; k = H / (b[3] - b[1]); G = affinity.scale(G, k, k, origin=(0, 0)); b = G.bounds
G = affinity.translate(G, 54 - (b[0] + b[2]) / 2, 54 - (b[1] + b[3]) / 2)
G = G.buffer(.3, quad_segs=16).buffer(-.3, quad_segs=16).simplify(.01); b = G.bounds
wl = b[1] + WLF * (b[3] - b[1])
top = G.intersection(box(-9, -9, 117, wl - GAP / 2)); bot = G.intersection(box(-9, wl + GAP / 2, 117, 117))
def path(g):
    s = ''
    for pg in getattr(g, 'geoms', [g]):
        c = list(pg.exterior.coords)[:-1]; s += 'M' + ' '.join(f'{x:.2f},{y:.2f}' for x, y in c) + 'Z'
    return s
HEAD = '''<?xml version="1.0" encoding="utf-8"?>
<!-- %s -->
<!-- Generated by tools/icon/handset_icon.py; edit the generator, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
'''
def doc(note, c1, c2):
    return (HEAD % note + f'    <path android:fillColor="#{c1}" android:pathData="{path(top)}" />\n'
            f'    <path android:fillColor="#{c2}" android:pathData="{path(bot)}" />\n</vector>\n')
R = os.path.join(HERE, '../../app/src/main/res/drawable/')
open(R + 'ic_launcher_foreground.xml', 'w').write(doc('A solid handset: navy above the water line, blue below, a thin paper gap between.', NAVY, BLUE))
open(R + 'ic_launcher_monochrome.xml', 'w').write(doc('The same mark in one colour for themed icons.', 'FF000000', 'FF000000'))
